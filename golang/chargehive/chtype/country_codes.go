var alpha2Country = func() map[string]CountryCode {
	countries := make(map[string]CountryCode, len(countryAlpha2))
	for country, alpha2 := range countryAlpha2 {
		countries[alpha2] = country
	}
	return countries
}()

// Alpha2 is the ISO 3166-1 alpha-2 code of the country x stands for, or "" when it stands for none, as
// COUNTRY_CODE_INVALID and COUNTRY_CODE_GLOBAL do.
func (x CountryCode) Alpha2() string {
	return countryAlpha2[x]
}

// CountryCodeFromAlpha2 is the CountryCode of an ISO 3166-1 alpha-2 code in any case, or COUNTRY_CODE_INVALID for a
// code no CountryCode stands for.
func CountryCodeFromAlpha2(alpha2 string) CountryCode {
	return alpha2Country[strings.ToUpper(strings.TrimSpace(alpha2))]
}
